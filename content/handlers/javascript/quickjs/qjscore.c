void js_handle_new_element(jsthread *thread, struct dom_element *node)
{
	assert(thread);
	assert(node);
	dom_namednodemap *map;
	dom_exception exc;
	dom_ulong idx;
	dom_ulong siz;
	dom_attr *attr = NULL;
	dom_string *key = NULL;
	dom_string *nodename;
	bool is_body = false;

	exc = dom_node_get_node_name(node, &nodename);
	if (exc != DOM_NO_ERR) return;

	if (nodename == corestring_dom_BODY)
		is_body = true;

	dom_string_unref(nodename);

	exc = dom_node_get_attributes(node, &map);
	if (exc != DOM_NO_ERR) return;
	if (map == NULL) return;

	qjs_enter_thread(thread);

	exc = dom_namednodemap_get_length(map, &siz);
	if (exc != DOM_NO_ERR) goto out;

	for (idx = 0; idx < siz; idx++) {
		exc = dom_namednodemap_item(map, idx, &attr);
		if (exc != DOM_NO_ERR) goto out;
		exc = dom_attr_get_name(attr, &key);
		if (exc != DOM_NO_ERR) goto out;
		if (is_body && (
			    key == corestring_dom_onblur ||
			    key == corestring_dom_onerror ||
			    key == corestring_dom_onfocus ||
			    key == corestring_dom_onload ||
			    key == corestring_dom_onresize ||
			    key == corestring_dom_onscroll)) {
			goto skip_register;
		}
		if (dom_string_length(key) > 2) {
			const uint8_t *data =
				(const uint8_t *)dom_string_data(key);
			if (data[0] == 'o' && data[1] == 'n') {
				dom_string *sub = NULL;
				exc = dom_string_substr(
					key, 2, dom_string_length(key),
					&sub);
				if (exc == DOM_NO_ERR) {
					qjsw_register_event_listener_for(
						thread->ctx,
						(struct dom_element *)node,
						sub, false);
					dom_string_unref(sub);
				}
			}
		}
	skip_register:
		dom_string_unref(key); key = NULL;
		dom_node_unref(attr); attr = NULL;
	}

out:
	if (key != NULL)
		dom_string_unref(key);
	if (attr != NULL)
		dom_node_unref(attr);

	dom_namednodemap_unref(map);
	qjs_leave_thread(thread);
}

void js_event_cleanup(jsthread *thread, struct dom_event *evt)
{
	assert(thread);
	qjs_enter_thread(thread);

	JSContext *ctx = thread->ctx;
	JSValue global = JS_GetGlobalObject(ctx);
	JSValue event_map = JS_GetPropertyStr(ctx, global, QJS_EVENT_MAP);

	if (!JS_IsUndefined(event_map) && !JS_IsException(event_map)) {
		/* Delete the event wrapper from the cache using pointer as key */
		char key[32];
		snprintf(key, sizeof(key), "%p", (void *)evt);
		JSAtom atom = JS_NewAtom(ctx, key);
		JS_DeleteProperty(ctx, event_map, atom, 0);
		JS_FreeAtom(ctx, atom);
	}

	JS_FreeValue(ctx, event_map);
	JS_FreeValue(ctx, global);

	qjs_leave_thread(thread);
}

