/* Execution timeout: 10 seconds (matches original JS_EXEC_TIMEOUT_MS=10000) */
#define JS_EXEC_TIMEOUT_NS (10ULL * 1000000000ULL)

/* ── Heap ──────────────────────────────────────────────────────────────────── */
struct jsheap {
	JSRuntime      *rt;
	int             timeout_secs;
	bool            pending_destroy;
	unsigned int    live_threads;
	struct timespec exec_start;   /**< monotonic clock at start of js_exec */
	bool            exec_timing;  /**< true while exec_start is valid */
	unsigned int    exec_count;   /**< total js_exec calls (for periodic GC/logging) */
};

/* ── Thread ────────────────────────────────────────────────────────────────── */
struct jsthread {
	JSContext    *ctx;
	jsheap       *heap;
	bool          pending_destroy;
	unsigned int  in_use;
};

/* ── Forward declarations for jsthread access from ctx ───────────────────── */

static jsthread *qjs_thread_from_ctx(JSContext *ctx)
{
	return (jsthread *)JS_GetContextOpaque(ctx);
}

/* ── Interrupt handler (execution timeout) ───────────────────────────────── */

static int qjs_interrupt_handler(JSRuntime *rt, void *opaque)
{
	(void)rt;
	jsheap *heap = (jsheap *)opaque;

	if (!heap->exec_timing)
		return 0;

	struct timespec now;
	clock_gettime(CLOCK_MONOTONIC, &now);

	uint64_t elapsed_ns =
		(uint64_t)(now.tv_sec  - heap->exec_start.tv_sec)  * 1000000000ULL +
		(uint64_t)(now.tv_nsec - heap->exec_start.tv_nsec);

	if (elapsed_ns > JS_EXEC_TIMEOUT_NS) {
		NSLOG(jserrors, WARNING, "QuickJS: execution timeout after ~10s");
		return 1; /* non-zero interrupts execution */
	}
	return 0;
}

static void qjs_reset_exec_timer(jsheap *heap)
{
	clock_gettime(CLOCK_MONOTONIC, &heap->exec_start);
	heap->exec_timing = true;
}

/* ── Exported timer reset — called from qjsw_helpers.c ──────────────────── */

void qjs_reset_exec_timer_from_ctx(JSContext *ctx)
{
	jsthread *t = qjs_thread_from_ctx(ctx);
	if (t != NULL)
		qjs_reset_exec_timer(t->heap);
}

/* ── Error logging helper ────────────────────────────────────────────────── */

static void qjs_log_exception(JSContext *ctx)
{
	JSValue exc = JS_GetException(ctx);
	if (!JS_IsNull(exc) && !JS_IsUndefined(exc)) {
		/* Print error message */
		const char *msg = JS_ToCString(ctx, exc);
		NSLOG(jserrors, WARNING, "QuickJS exception: %s",
		      msg ? msg : "(unknown)");
		JS_FreeCString(ctx, msg);
		/* Also print stack trace if available */
		JSValue stk = JS_GetPropertyStr(ctx, exc, "stack");
		if (!JS_IsUndefined(stk)) {
			const char *s = JS_ToCString(ctx, stk);
			NSLOG(jserrors, WARNING, "  stack: %s",
			      s ? s : "(no stack)");
			JS_FreeCString(ctx, s);
		}
		JS_FreeValue(ctx, stk);
	}
	JS_FreeValue(ctx, exc);
}

/* ── JS_DeletePropertyStr helper (not in public API before 2023) ─────────── */

static void qjs_delete_global_prop(JSContext *ctx, const char *name)
{
	JSValue global = JS_GetGlobalObject(ctx);
	JSAtom atom = JS_NewAtom(ctx, name);
	JS_DeleteProperty(ctx, global, atom, 0);
	JS_FreeAtom(ctx, atom);
	JS_FreeValue(ctx, global);
}

/* ── Embed helper: eval a byte-array script ──────────────────────────────── */

static bool qjs_eval_bytes(JSContext *ctx,
			    const unsigned char *src, unsigned int src_len,
			    const char *filename)
{
	JSValue val = JS_Eval(ctx, (const char *)src, src_len, filename,
			      JS_EVAL_TYPE_GLOBAL);
	if (JS_IsException(val)) {
		qjs_log_exception(ctx);
		JS_FreeValue(ctx, val);
		return false;
	}
	JS_FreeValue(ctx, val);
	return true;
}

