/* ── Internal stash property names ──────────────────────────────────────────
 * These are stored as plain string properties on the JS global object.
 * Duktape used \xFF\xFF hidden properties; QuickJS has no equivalent so we
 * use printable but unlikely-to-clash names.                                  */
