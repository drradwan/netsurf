bool js_fire_event(jsthread *thread, const char *type,
		   struct dom_document *doc, struct dom_node *target)
{
	dom_exception exc;
	dom_event *evt;
	dom_event_target *body;

	NSLOG(quickjs, DEBUG, "js_fire_event: %s (doc=%p, target=%p)", type, doc,
	      target);
	ALOG_QJS("fire_event: %s (doc=%p, target=%p)", type, (void *)doc,
		 (void *)target);

	if (strcmp(type, "load") != 0)
		return true;

	/* Element-targeted load events (e.g. iframe onload) */
	if (target != NULL) {
		JSContext *ctx = thread->ctx;
		JSValue node = qjsw_push_node(ctx, target);
		if (!JS_IsUndefined(node)) {
			/* Fire inline onload handler */
			JSValue handler = JS_GetPropertyStr(ctx, node, "onload");
			if (JS_IsFunction(ctx, handler)) {
				JSValue event_obj = JS_NewObject(ctx);
				JS_SetPropertyStr(ctx, event_obj, "type",
					JS_NewString(ctx, "load"));
				JS_SetPropertyStr(ctx, event_obj, "target",
					JS_DupValue(ctx, node));
				JSValue result = qjsw_pcall(ctx, handler,
					node, 1, &event_obj, true);
				JS_FreeValue(ctx, result);
				JS_FreeValue(ctx, event_obj);
			}
			JS_FreeValue(ctx, handler);
		}
		JS_FreeValue(ctx, node);
		return true;
	}

	exc = dom_event_create(&evt);
	if (exc != DOM_NO_ERR) return true;
	exc = dom_event_init(evt, corestring_dom_load, false, false);
	if (exc != DOM_NO_ERR) {
		dom_event_unref(evt);
		return true;
	}

	qjs_enter_thread(thread);
	JSContext *ctx = thread->ctx;

	/* Look for "load" handler on Window (global object) */
	JSValue global = JS_GetGlobalObject(ctx);
	JSValue handler = qjsw_get_event_handler(ctx, global, NULL,
						  "load", 4);

	if (JS_IsUndefined(handler)) {
		/* Try body element's onload handler */
		exc = dom_html_document_get_body(doc, &body);
		if (exc != DOM_NO_ERR) {
			JS_FreeValue(ctx, global);
			dom_event_unref(evt);
			qjs_leave_thread(thread);
			return true;
		}
		if (body != NULL) {
			JSValue body_val = qjsw_push_node(ctx,
					(struct dom_node *)body);
			handler = qjsw_get_event_handler(ctx, body_val,
					body, "load", 4);
			JS_FreeValue(ctx, body_val);
			dom_node_unref(body);
		}
	}

	if (JS_IsUndefined(handler)) {
		JS_FreeValue(ctx, global);
		dom_event_unref(evt);
		qjs_leave_thread(thread);
		return true;
	}

	/* Call handler with Window as this, event as argument */
	JSValue evt_val = qjsw_push_event(ctx, evt);
	JSValue result = qjsw_pcall(ctx, handler, global, 1, &evt_val, true);
	thread->heap->exec_timing = false;

	JS_FreeValue(ctx, result);
	JS_FreeValue(ctx, evt_val);
	JS_FreeValue(ctx, global);
	JS_FreeValue(ctx, handler);

	js_event_cleanup(thread, evt);
	dom_event_unref(evt);
	qjs_leave_thread(thread);
	return true;
}

